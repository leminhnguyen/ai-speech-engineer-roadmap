"""Validate sota/data/entries.yaml and regenerate the SOTA tracker pages.

    python scripts/build_sota.py          # rewrite generated files
    python scripts/build_sota.py --check  # fail if generated files are stale (CI)
"""

from pathlib import Path
import re
import sys

import yaml


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "sota/data/entries.yaml"
TOPICS_DIR = ROOT / "sota/topics"
SOTA_README = ROOT / "sota/README.md"
ROOT_README = ROOT / "README.md"

REQUIRED = ("name", "title", "date", "topic", "type", "paper", "note")
TYPES = {"model", "survey", "benchmark", "dataset", "toolkit"}
DATE = re.compile(r"^\d{4}(-(0[1-9]|1[0-2]))?$")
LATEST_IN_ROOT = 5
LATEST_IN_SOTA = 10
HEADER = "<!-- Generated by scripts/build_sota.py from sota/data/entries.yaml. Do not edit by hand. -->"


def load():
    data = yaml.safe_load(DATA.read_text(encoding="utf-8"))
    topics, entries = data["topics"], data["entries"]
    errors, seen = [], set()
    for index, entry in enumerate(entries):
        label = entry.get("name", f"entry #{index}")
        for field in REQUIRED:
            if not entry.get(field):
                errors.append(f"{label}: missing '{field}'")
        entry["date"] = str(entry.get("date", ""))
        if not DATE.match(entry["date"]):
            errors.append(f"{label}: date must be YYYY-MM or YYYY")
        if entry.get("topic") not in topics:
            errors.append(f"{label}: unknown topic '{entry.get('topic')}'")
        if entry.get("type") not in TYPES:
            errors.append(f"{label}: type must be one of {sorted(TYPES)}")
        if label in seen:
            errors.append(f"{label}: duplicate name")
        seen.add(label)
    if errors:
        sys.exit("SOTA data is invalid:\n" + "\n".join(f"- {e}" for e in errors))
    return topics, sorted(entries, key=lambda e: (e["date"], e["name"]), reverse=True)


def links(entry):
    parts = [f"[paper]({entry['paper']})"]
    if entry.get("code") and entry["code"] != entry["paper"]:
        parts.append(f"[code]({entry['code']})")
    return " · ".join(parts)


def name_cell(entry):
    star = "⭐ " if entry.get("essential") else ""
    flag = " 🇻🇳" if "vi" in entry.get("tags", []) else ""
    return f"{star}**{entry['name']}**{flag}"


def topic_page(topic, entries):
    rows = [
        f"| {e['date']} | {name_cell(e)} | {e.get('org', '—')} | {e['type']} | {e['note']} | {links(e)} |"
        for e in entries
    ]
    return "\n".join([
        HEADER,
        "",
        f"# {topic['emoji']} {topic['title']}",
        "",
        f"> {' '.join(topic['summary'].split())}",
        "",
        f"[← Back to the SOTA tracker](../README.md) · {len(entries)} entries · newest first · ⭐ = must-read",
        "",
        "| Date | Work | Org | Type | Why it matters | Links |",
        "| :---: | --- | --- | :---: | --- | --- |",
        *rows,
        "",
    ])


def latest_table(entries, count, topics, topic_prefix):
    rows = [
        f"| {e['date']} | {name_cell(e)} | [{topics[e['topic']]['title']}]({topic_prefix}{e['topic']}.md) | {e['note']} |"
        for e in entries[:count]
    ]
    return "\n".join(["| Date | Work | Track | Why it matters |", "| :---: | --- | --- | --- |", *rows])


def topic_index(topics, entries):
    rows = []
    for key, topic in topics.items():
        items = [e for e in entries if e["topic"] == key]
        newest = items[0]["date"] if items else "—"
        rows.append(f"| {topic['emoji']} | [{topic['title']}](topics/{key}.md) | {len(items)} | {newest} |")
    return "\n".join(["| | Track | Entries | Newest |", "| :---: | --- | :---: | :---: |", *rows])


def replace_block(text, name, body):
    pattern = re.compile(rf"(<!-- BEGIN {name} -->\n).*?(<!-- END {name} -->)", re.S)
    if not pattern.search(text):
        sys.exit(f"Missing <!-- BEGIN {name} --> / <!-- END {name} --> markers.")
    return pattern.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)


def render():
    topics, entries = load()
    outputs = {}
    for key, topic in topics.items():
        outputs[TOPICS_DIR / f"{key}.md"] = topic_page(topic, [e for e in entries if e["topic"] == key])

    sota = SOTA_README.read_text(encoding="utf-8")
    sota = replace_block(sota, "TRACKS", topic_index(topics, entries))
    sota = replace_block(sota, "LATEST", latest_table(entries, LATEST_IN_SOTA, topics, "topics/"))
    outputs[SOTA_README] = sota

    root = ROOT_README.read_text(encoding="utf-8")
    root = replace_block(root, "LATEST", latest_table(entries, LATEST_IN_ROOT, topics, "sota/topics/"))
    outputs[ROOT_README] = root
    return outputs, len(entries), len(topics)


def main():
    check = "--check" in sys.argv
    outputs, n_entries, n_topics = render()
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            print("SOTA pages are out of date. Run `make sota` and commit the result:")
            print("\n".join(f"- {p.relative_to(ROOT)}" for p in stale))
            return 1
        print(f"SOTA check passed: {n_entries} entries in {n_topics} tracks.")
        return 0
    TOPICS_DIR.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
    print(f"SOTA pages built: {n_entries} entries in {n_topics} tracks, {len(stale)} file(s) updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
